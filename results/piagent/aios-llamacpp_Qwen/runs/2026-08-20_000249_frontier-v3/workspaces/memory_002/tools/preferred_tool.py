"""
preferred_tool.py
Reads durable memory (user preferences), applies at least two preferences
to the expense analysis, and writes a summary report.

Preference token: 7K9X2A
Preferences applied:
  - primary_language: Python → tool written in Python, no shell/awk/bash
  - tooling_style: simple  → minimal dependencies, single-file script
  - vcs_policy: no-commit → no git operations performed
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path

# ---------------------------------------------------------------------------
# Preference retrieval
# ---------------------------------------------------------------------------

BASE_DIR = Path(__file__).resolve().parents[1]  # workspace root

def load_preferences() -> dict:
    """Load durable memory from .agent_memory/preferences.json."""
    pref_path = BASE_DIR / ".agent_memory" / "preferences.json"
    with open(pref_path, encoding="utf-8") as f:
        return json.load(f)


# ---------------------------------------------------------------------------
# Core logic — applies preferences internally
# ---------------------------------------------------------------------------

PREFERENCE_TOKEN = "7K9X2A"


def analyse_expenses(input_path: Path) -> dict:
    """
    Analyse expenses.csv:
      - Sum totals per category (ignoring rows with missing/empty amounts).
      - Count total rows and valid rows.
      - Compute overall total.
    """
    rows = []
    with open(input_path, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            rows.append(row)

    category_totals: dict[str, float] = defaultdict(float)
    total_rows = len(rows)
    valid_rows = 0
    overall_total = 0.0

    for row in rows:
        amt_raw = row.get("amount", "").strip()
        if not amt_raw:
            continue  # skip missing amounts
        valid_rows += 1
        amt = float(amt_raw)
        overall_total += amt
        cat = row.get("category", "unknown")
        category_totals[cat] += amt

    return {
        "total_rows": total_rows,
        "valid_rows": valid_rows,
        "overall_total": round(overall_total, 2),
        "category_totals": dict(sorted(category_totals.items())),
    }


def format_report(analysis: dict, prefs: dict) -> str:
    """Build a Markdown report incorporating preference context."""
    lines: list[str] = []
    lines.append("# Expense Analysis Report")
    lines.append("")
    lines.append("## Metadata")
    lines.append("")
    lines.append(f"- **Preference token**: `{prefs.get('preference_token', '')}`")
    lines.append(f"- **Primary language**: {prefs.get('primary_language', '')}")
    lines.append(f"- **Tooling style**: {prefs.get('tooling_style', '')}")
    lines.append(f"- **VCS policy**: {prefs.get('vcs_policy', '')}")
    lines.append("")
    lines.append("## Summary")
    lines.append("")
    lines.append(f"- Total expense rows: {analysis['total_rows']}")
    lines.append(f"- Valid amounts:      {analysis['valid_rows']}")
    lines.append(f"- Overall total:      ${analysis['overall_total']:.2f}")
    lines.append("")
    lines.append("## Category Breakdown")
    lines.append("")
    lines.append("| Category | Total |")
    lines.append("|----------|-------|")
    for cat, total in analysis["category_totals"].items():
        lines.append(f"| {cat} | ${total:.2f} |")
    lines.append("")
    lines.append("## Preference Application")
    lines.append("")
    lines.append(
        "This report was generated by a Python tool "
        "(`primary_language: Python`) using a simple, "
        "single-file design (`tooling_style: simple`). "
        "No version-control commits were made "
        "(`vcs_policy: no-commit`)."
    )
    lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# CLI entry point
# ---------------------------------------------------------------------------


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Expense analysis with durable-memory preferences"
    )
    parser.add_argument(
        "--input",
        default=str(BASE_DIR / "data" / "expenses.csv"),
        help="Path to expenses CSV",
    )
    parser.add_argument(
        "--output",
        default=str(BASE_DIR / "reports" / "memory_application.md"),
        help="Path for output report",
    )
    args = parser.parse_args()

    # 1. Load durable memory
    prefs = load_preferences()

    # 2. Apply preferences: primary_language & tooling_style
    #    (checked at runtime via prefs dict)
    assert prefs.get("primary_language") == "Python", (
        "Expected primary_language=Python"
    )
    assert prefs.get("tooling_style") == "simple", (
        "Expected tooling_style=simple"
    )

    # 3. Analyse expenses
    analysis = analyse_expenses(Path(args.input))

    # 4. Format report with preference token in metadata
    report = format_report(analysis, prefs)

    # 5. Write report
    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(report, encoding="utf-8")

    print(f"Report written to {out_path}")
    print(f"Preference token embedded: {PREFERENCE_TOKEN}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
