#!/usr/bin/env python3
"""
Monthly Sales Reporter

Reads data/sales.csv, validates the header and numeric fields,
calculates total revenue and units, and saves the summary
as reports/monthly-sales.md.

Usage:
    python projects/monthly_sales.py [--input DATA_PATH] [--output REPORT_PATH]
"""

import csv
import os
import sys


def load_sales(path):
    """Load sales CSV and return header + rows."""
    with open(path, newline="") as fh:
        reader = csv.reader(fh)
        header = next(reader)
        rows = list(reader)
    return header, rows


def validate_header(header):
    """Validate that the header matches the expected schema."""
    expected = ["date", "product", "units", "revenue"]
    if header != expected:
        raise ValueError(
            f"Invalid header: expected {expected}, got {header}"
        )


def validate_numeric_fields(rows):
    """Ensure units and revenue columns are numeric.
    Returns (total_units, total_revenue, row_errors)."""
    total_units = 0
    total_revenue = 0.0
    row_errors = []

    for i, row in enumerate(rows, start=2):  # start=2 because CSV is 1-indexed (header is row 1)
        if len(row) < 4:
            row_errors.append(f"Row {i}: expected 4 fields, got {len(row)}")
            continue
        try:
            units = float(row[2])
            revenue = float(row[3])
            total_units += units
            total_revenue += revenue
        except ValueError as e:
            row_errors.append(f"Row {i}: non-numeric value — {e}")

    return total_units, total_revenue, row_errors


def generate_report(total_units, total_revenue, row_errors, header, rows):
    """Build the markdown report string."""
    lines = [
        "# Monthly Sales Summary",
        "",
        "## Data Overview",
        "",
        f"- **Total Units Sold:** {int(total_units)}",
        f"- **Total Revenue:** ${total_revenue:,.2f}",
        "",
    ]

    # Per-product breakdown
    product_stats = {}
    for row in rows:
        if len(row) < 4:
            continue
        try:
            product = row[1]
            units = float(row[2])
            revenue = float(row[3])
        except (ValueError, IndexError):
            continue
        product_stats.setdefault(product, {"units": 0, "revenue": 0.0})
        product_stats[product]["units"] += units
        product_stats[product]["revenue"] += revenue

    lines.append("## Product Breakdown")
    lines.append("")
    lines.append("| Product | Units | Revenue |")
    lines.append("|---------|-------|---------|")
    for product in sorted(product_stats):
        s = product_stats[product]
        lines.append(
            f"| {product} | {int(s['units'])} | ${s['revenue']:,.2f} |"
        )
    lines.append("")

    # Row errors
    if row_errors:
        lines.append("## Validation Warnings")
        lines.append("")
        for err in row_errors:
            lines.append(f"- ⚠️ {err}")
        lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("*Report generated by monthly_sales.py*")
    lines.append("")

    return "\n".join(lines)


def main():
    # Resolve paths relative to workspace root
    workspace = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    default_input = os.path.join(workspace, "data", "sales.csv")
    default_output = os.path.join(workspace, "reports", "monthly-sales.md")

    # Simple CLI arg parsing
    input_path = default_input
    output_path = default_output
    i = 1
    while i < len(sys.argv):
        if sys.argv[i] == "--input" and i + 1 < len(sys.argv):
            input_path = sys.argv[i + 1]
            i += 2
        elif sys.argv[i] == "--output" and i + 1 < len(sys.argv):
            output_path = sys.argv[i + 1]
            i += 2
        else:
            i += 1

    # 1. Load
    header, rows = load_sales(input_path)

    # 2. Validate header
    validate_header(header)

    # 3. Validate numeric fields and calculate totals
    total_units, total_revenue, row_errors = validate_numeric_fields(rows)

    # 4. Generate report
    report = generate_report(total_units, total_revenue, row_errors, header, rows)

    # 5. Save
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w") as fh:
        fh.write(report)

    print(f"Report written to {output_path}")
    print(f"Total units: {int(total_units)}, Total revenue: ${total_revenue:,.2f}")
    if row_errors:
        print(f"Validation warnings: {len(row_errors)}")


if __name__ == "__main__":
    main()
